using Microsoft.AspNetCore.Hosting;
using Microsoft.AspNetCore.Mvc.Testing;
using PixelOffice.API.Data;

namespace PixelOffice.API.Tests.Fixtures;

// In-process API host for tests that need no database.
// The API gets its connection string and signing key from the AppHost; tests run without the AppHost
// (plan.md), so this supplies a placeholder connection string that is never opened, a test signing key,
// and turns off the database health check and startup migration.
// Tests that need a database use DatabaseApiFactory.
public class ApiFactory : WebApplicationFactory<Program>
{
    /// <summary>Signing key used by every test host. Test-only; the real key is generated by the AppHost.</summary>
    public const string TestSigningKey = "test-signing-key-for-pixel-office-tests-only-0123456789";

    public ApiFactory() => UseHttps(ClientOptions);

    /// <summary>
    /// Test clients call the API over HTTPS, like real callers. Over HTTP, UseHttpsRedirection redirects,
    /// and HttpClient drops the Authorization header when it follows a redirect.
    /// </summary>
    public static void UseHttps(WebApplicationFactoryClientOptions options) =>
        options.BaseAddress = new Uri("https://localhost");

    protected override void ConfigureWebHost(IWebHostBuilder builder)
    {
        // UseSetting is applied before Program.cs reads configuration, unlike ConfigureAppConfiguration.
        builder.UseSetting("ConnectionStrings:pixeloffice", "Host=unused.invalid;Database=pixeloffice");
        builder.UseSetting("Aspire:Npgsql:EntityFrameworkCore:PostgreSQL:DisableHealthChecks", "true");
        builder.UseSetting(DatabaseStartup.ApplyOnStartupKey, "false");
        builder.UseSetting("Jwt:SigningKey", TestSigningKey);
    }
}
